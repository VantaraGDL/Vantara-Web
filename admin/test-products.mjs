import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {filterProducts,numberOrNull,saveChanges,allRows} from './js/products-data.js';
const source=fs.readFileSync(new URL('../js/productos.js',import.meta.url),'utf8');
const catalog=vm.runInNewContext(source.slice(0,source.indexOf('\n];')+3)+'\nproducts');
const rows=Array.from(catalog,p=>({...p,brand_id:p.brand,category_id:p.category,published:false,product_variants:[{stock:p.stock?1:null}]}));
assert.equal(rows.length,32);
assert.equal(filterProducts(rows,{}).length,32);
assert.equal(filterProducts(rows,{brand:'Alo'}).length,6);
assert.equal(filterProducts(rows,{search:'light oatmeal'}).length,2);
assert.equal(filterProducts(rows,{status:'published'}).length,0);
assert.equal(filterProducts(rows,{stock:true}).length,31);
assert.equal(filterProducts(rows,{brand:'Alo',category:'Shorts'}).length,0);
assert.equal(numberOrNull(''),null);assert.equal(numberOrNull('0',true),0);
for(const value of ['-1','1.5','Infinity'])assert.throws(()=>numberOrNull(value,true));
assert.throws(()=>numberOrNull('12.345'));
const db={products:{id:2,name:'Original'},product_variants:{id:1,product_id:2,stock:null}};
let fail=false;
const client={async rpc(name,args){assert.equal(name,'update_catalog_product');if(fail)return {error:{message:'test failure'}};Object.assign(db.products,args.p_changes);for(const v of args.p_variants)db.product_variants.stock=v.stock;return {error:null};}};
const original={id:2,name:'Original',product_variants:[{id:1,stock:null}]};
await saveChanges(client,original,{name:'Prueba'},[{id:1,stock:3}]);
assert.equal(db.products.name,'Prueba');assert.equal(db.product_variants.stock,3);
assert.equal(original.name,db.products.name);
fail=true;
await assert.rejects(saveChanges(client,original,{name:'Otro'},[{id:1,stock:0}]),/No se pudo guardar/);
assert.equal(original.product_variants[0].stock,3);
fail=false;await saveChanges(client,original,{name:'Original'},[{id:1,stock:null}]);
assert.equal(db.products.name,'Original');assert.equal(db.product_variants.stock,null);
const readClient={from(){return {select(){return this;},order(){return this;},async range(a,b){return {data:rows.slice(a,b+1),error:null};}};}};
assert.equal((await allRows(readClient,'products','*')).length,32);
console.log('PASS: listado 32, búsqueda, filtros, validación precio/stock, guardar campo y stock, fallo atómico, reintento y reversión simulada.');
